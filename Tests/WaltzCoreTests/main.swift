    assertions += 1
    if lhs != rhs { failures += 1; print("FAIL \(URL(fileURLWithPath: file).lastPathComponent):\(line): \(lhs) != \(rhs)") }
}
func XCTAssertNil<T>(_ value: T?, file: String = #filePath, line: Int = #line) {
    assertions += 1
    if value != nil { failures += 1; print("FAIL \(file):\(line): expected nil") }
}
